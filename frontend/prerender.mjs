// Build-time rendering keeps the page readable without JavaScript or a Node server.
import { createServer } from 'vite';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { writeFileSync } from 'node:fs';

const server = await createServer({
  configFile: 'frontend/vite.config.ts',
  server: { middlewareMode: true },
  appType: 'custom',
});
const replacements = {
  __URL_HOME__: "{{ url_for('index') }}",
  __URL_FUNDRAISING__: "{{ url_for('fundraising') }}",
  __URL_PRIVACY__: "{{ url_for('privacy') }}",
  __URL_CAMPAIGN__: "{{ url_for('campaign.index') }}",
  __VOLUNTEER_ENDPOINT__: "{{ url_for('campaign.add_volunteer') }}",
};
function save(name, element) {
  let html = renderToStaticMarkup(element);
  for (const [marker, value] of Object.entries(replacements)) html = html.replaceAll(marker, value);
  if (/__(?:URL|VOLUNTEER|FUNDRAISING)_/.test(html)) throw new Error(`Unresolved prerender marker in ${name}`);
  writeFileSync(`mielenosoitukset_fi/templates/kampanja/_${name}_fallback.html`,
    `{# Generated by npm run build from the React page. Do not edit by hand. #}\n${html}\n`);
}
try {
  const { CampaignPage } = await server.ssrLoadModule('/src/pages/CampaignPage.tsx');
  const { ConfirmationPage } = await server.ssrLoadModule('/src/pages/ConfirmationPage.tsx');
  const { volunteerMessages } = await server.ssrLoadModule('/src/data/campaign.ts');
  save('campaign', createElement(CampaignPage, {
    urls: { home: '__URL_HOME__', fundraising: '__URL_FUNDRAISING__', privacy: '__URL_PRIVACY__' },
    serverFallback: true,
    volunteer: { endpoint: '__VOLUNTEER_ENDPOINT__', messages: volunteerMessages },
    newsletter: { endpoint: 'https://mailist.luova.club/signup', listId: '68d26ca27f8e9dee7c846a22' },
  }));
  for (const status of ['success', 'invalid', 'expired']) {
    save(`confirmation_${status}`, createElement(ConfirmationPage, {
      status, urls: { home: '__URL_HOME__', campaign: '__URL_CAMPAIGN__' },
    }));
  }
} finally {
  await server.close();
}
